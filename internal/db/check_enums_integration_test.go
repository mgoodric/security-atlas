//go:build integration

// #2328 — the values of the CHECK-constrained text columns the web app
// labels, read from the migrated database.
//
// sqlc only generates Go types for Postgres enums, so models.go cannot tell
// web/lib/labels/enum-labels.test.ts what an action plan's or an audit
// period's status may be. This test reads each column's CHECK constraint
// with pg_get_constraintdef and diffs the values against the committed
// golden web/lib/contracts/check-enums.golden.json, which the label test
// reads. A migration that adds a value fails here until the golden is
// regenerated, and the label test then fails until the value has a label.
//
// Regenerate after an intentional constraint change:
//
//	go test -tags=integration ./internal/db/ -run TestCheckEnums -update
//
// Lives in internal/db/ so the local `just test-integration` package set
// runs it as well as CI.

package db_test

import (
	"context"
	"encoding/json"
	"flag"
	"os"
	"reflect"
	"regexp"
	"testing"
	"time"
)

const checkEnumsGolden = "../../web/lib/contracts/check-enums.golden.json"

var checkEnumsUpdate = flag.Bool("update", false, "rewrite web/lib/contracts/check-enums.golden.json")

// checkEnumColumns maps each ENUM_LABELS group to the column whose CHECK
// constraint holds its values.
var checkEnumColumns = []struct {
	name, table, column string
}{
	{"ActionPlanStatus", "action_plans", "status"},
	{"AuditPeriodStatus", "audit_periods", "status"},
}

// checkLiteral matches one value in a rendered IN-list:
// CHECK ((status = ANY (ARRAY['open'::text, 'frozen'::text])))
var checkLiteral = regexp.MustCompile(`'((?:[^']|'')*)'::text`)

type checkEnumsFile struct {
	Comment string              `json:"_comment"`
	Enums   map[string][]string `json:"enums"`
}

func TestCheckEnums_MatchGolden(t *testing.T) {
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()

	got := checkEnumsFile{
		Comment: "Generated by internal/db/check_enums_integration_test.go from pg_get_constraintdef; do not edit. Regenerate: go test -tags=integration ./internal/db/ -run TestCheckEnums -update",
		Enums:   map[string][]string{},
	}
	for _, c := range checkEnumColumns {
		// The single-column CHECK on the column; multi-column coherence
		// checks (status with frozen_at) are not value lists.
		rows, err := appPool.Query(ctx, `
			SELECT pg_get_constraintdef(c.oid)
			FROM pg_constraint c
			JOIN pg_attribute a
			  ON a.attrelid = c.conrelid AND a.attnum = c.conkey[1]
			WHERE c.conrelid = $1::regclass
			  AND c.contype = 'c'
			  AND cardinality(c.conkey) = 1
			  AND a.attname = $2`, c.table, c.column)
		if err != nil {
			t.Fatalf("%s.%s: read constraints: %v", c.table, c.column, err)
		}
		var values []string
		for rows.Next() {
			var def string
			if err := rows.Scan(&def); err != nil {
				t.Fatalf("%s.%s: scan: %v", c.table, c.column, err)
			}
			for _, m := range checkLiteral.FindAllStringSubmatch(def, -1) {
				values = append(values, m[1])
			}
		}
		if err := rows.Err(); err != nil {
			t.Fatalf("%s.%s: rows: %v", c.table, c.column, err)
		}
		if len(values) == 0 {
			t.Fatalf("%s.%s: no CHECK value list found", c.table, c.column)
		}
		got.Enums[c.name] = values
	}

	out, err := json.MarshalIndent(got, "", "  ")
	if err != nil {
		t.Fatalf("marshal: %v", err)
	}
	out = append(out, '\n')

	if *checkEnumsUpdate {
		if err := os.WriteFile(checkEnumsGolden, out, 0o644); err != nil {
			t.Fatalf("write golden: %v", err)
		}
		return
	}
	// Compared as data, not bytes: prettier reflows the committed file.
	raw, err := os.ReadFile(checkEnumsGolden)
	if err != nil {
		t.Fatalf("read golden: %v", err)
	}
	var want checkEnumsFile
	if err := json.Unmarshal(raw, &want); err != nil {
		t.Fatalf("decode golden: %v", err)
	}
	if !reflect.DeepEqual(want.Enums, got.Enums) {
		t.Fatalf("check-enums golden drifted; regenerate with -update.\nwant: %v\ngot:  %v", want.Enums, got.Enums)
	}
}
