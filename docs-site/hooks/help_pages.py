"""mkdocs hook — #2143 module help pages.

Publishes each in-app help file `web/help/modules/<id>.md` as the docs
page `help/<id>.md`, so the app's "How this works" panel and the docs site
are published from one file. The generated pages are gitignored; edit the
help file, not the page.

The page is the help file's body under its title, then its diagrams (copied
from `web/public/help/diagrams/`) and its key terms, each linking to its
entry on the Terms page (generated by `terms_page.py` from the same
`web/help/terms.json` the panel reads). The app's "Read more" link points
here (`web/lib/help/modules.ts` `helpDocsHref`).

The front matter is the small YAML subset `web/lib/help/modules.ts`
parses; PyYAML (an mkdocs dependency) reads it here.
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path
from typing import Any

import yaml

_REPO_ROOT = Path(__file__).resolve().parents[2]
_SRC_DIR = _REPO_ROOT / "web" / "help" / "modules"
_SRC_DIAGRAMS = _REPO_ROOT / "web" / "public" / "help" / "diagrams"
_SRC_TERMS = _REPO_ROOT / "web" / "help" / "terms.json"
_DEST_DIR = _REPO_ROOT / "docs-site" / "docs" / "help"


def on_pre_build(config: dict[str, Any], **kwargs: Any) -> None:
    """mkdocs hook entry: writes the help pages before files are collected.

    Args:
        config: mkdocs build config dict (unused but required by hook
            signature).
        **kwargs: forward-compat for future mkdocs hook args.
    """
    sources = sorted(_SRC_DIR.glob("*.md"))
    if not sources:
        raise FileNotFoundError(f"#2143 help pages: no help files in {_SRC_DIR}")
    terms = {t["id"]: t for t in json.loads(_SRC_TERMS.read_text(encoding="utf-8"))["terms"]}
    if _DEST_DIR.exists():
        shutil.rmtree(_DEST_DIR)
    (_DEST_DIR / "diagrams").mkdir(parents=True)
    for src in sources:
        meta, body = split_front_matter(src.read_text(encoding="utf-8"))
        for diagram in meta.get("diagrams") or []:
            shutil.copyfile(_SRC_DIAGRAMS / diagram["src"], _DEST_DIR / "diagrams" / diagram["src"])
        (_DEST_DIR / f"{meta['id']}.md").write_text(
            render_help_page(meta, body, terms), encoding="utf-8"
        )


def split_front_matter(source: str) -> tuple[dict[str, Any], str]:
    """Return the front matter and the body of a help file."""
    lines = source.replace("\r\n", "\n").split("\n")
    if lines[0] != "---" or "---" not in lines[1:]:
        raise ValueError("#2143 help file must open with a --- front matter block")
    end = lines.index("---", 1)
    return yaml.safe_load("\n".join(lines[1:end])) or {}, "\n".join(lines[end + 1 :]).strip()


def render_help_page(meta: dict[str, Any], body: str, terms: dict[str, dict[str, str]]) -> str:
    """Return the docs page Markdown for one module's help."""
    lines = [
        f"# {meta['title']}",
        "",
        f"<!-- Generated from web/help/modules/{meta['id']}.md by"
        " docs-site/hooks/help_pages.py. Edit the help file, not this page. -->",
        "",
        "This is the help shown by the **?** button on this part of the app.",
        "",
        body,
        "",
    ]
    for diagram in meta.get("diagrams") or []:
        lines += [f"![{diagram['alt']}](diagrams/{diagram['src']})", ""]
    known = [terms[t] for t in meta.get("terms") or [] if t in terms]
    if known:
        lines += ["## Key terms", ""]
        for term in known:
            lines += [f"- [{term['name']}](../terms.md#{term['id']}): {term['short']}"]
        lines += [""]
    return "\n".join(lines)
