// #2394 — the web client's platform types, generated from the OpenAPI spec.
//
//   npm run openapi:types    (from web/) write lib/api/generated/openapi.d.ts
//   npm run openapi:check    (from web/) fail when the committed file is stale
//
// docs/openapi.yaml is written by cmd/atlas-openapi, which reflects the
// response schemas from the Go wire structs, and openapi-drift-check keeps
// it current. This keeps the TypeScript side current with it, so a Go
// field rename fails the web typecheck wherever the old name is used.

import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import openapiTS, { astToString } from "openapi-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const WEB = join(here, "..", "..");
const SPEC = join(WEB, "..", "docs", "openapi.yaml");
const OUT = join(WEB, "lib", "api", "generated", "openapi.d.ts");

const HEADER = `/**
 * This file was auto-generated by openapi-typescript.
 * Do not make direct changes to the file.
 */

`;

async function generate() {
  const ast = await openapiTS(pathToFileURL(SPEC));
  return HEADER + astToString(ast);
}

const want = await generate();

if (process.argv.includes("--check")) {
  let have = "";
  try {
    have = await readFile(OUT, "utf8");
  } catch {
    // A missing file is stale.
  }
  if (have !== want) {
    console.error(
      "lib/api/generated/openapi.d.ts is stale against docs/openapi.yaml.\n" +
        "Run `npm run openapi:types` in web/ and commit the result.",
    );
    process.exit(1);
  }
  console.log("lib/api/generated/openapi.d.ts matches docs/openapi.yaml");
} else {
  await writeFile(OUT, want);
  console.log("wrote lib/api/generated/openapi.d.ts");
}
