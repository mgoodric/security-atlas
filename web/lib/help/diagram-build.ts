// #2148 — the build side of lifecycle diagrams: Node only, never imported
// by app code.
//
// `scripts/render-help-diagrams.mjs` uses this to theme, clean and stamp
// each SVG it renders; `diagrams.test.ts` uses it to prove the committed
// SVGs are current and clean. Keeping both on one module means the test
// recomputes exactly the stamp the renderer wrote.
//
// The stamp is a sha256 over everything that shapes a rendered SVG: the
// Mermaid version, the theme's token values from `app/globals.css`, the
// token-to-Mermaid mapping below, and the diagram source. Comparing stamps
// rather than SVG bytes keeps the check deterministic, because Mermaid
// measures label text with whatever fonts the rendering machine has.

import { createHash } from "node:crypto";

export type DiagramTheme = "light" | "dark";

/** Mermaid `base` theme variables, each set from one app theme token. */
export const MERMAID_THEME_MAP: Readonly<Record<string, string>> = {
  background: "background",
  mainBkg: "muted",
  primaryColor: "muted",
  primaryTextColor: "foreground",
  primaryBorderColor: "muted-foreground",
  secondaryColor: "card",
  tertiaryColor: "card",
  lineColor: "muted-foreground",
  textColor: "foreground",
  stateBkg: "muted",
  stateBorder: "muted-foreground",
  stateLabelColor: "foreground",
  transitionColor: "muted-foreground",
  transitionLabelColor: "foreground",
  labelBackgroundColor: "background",
  edgeLabelBackground: "background",
  compositeBackground: "card",
  specialStateColor: "foreground",
  innerEndBackground: "foreground",
};

/** Every token the map reads. */
export const THEME_TOKENS: readonly string[] = [
  ...new Set(Object.values(MERMAID_THEME_MAP)),
].sort();

const BLOCKS: Record<DiagramTheme, RegExp> = {
  light: /(?:^|\n):root,\s*\.paper\s*\{([^}]*)\}/,
  dark: /(?:^|\n)\.dark\s*\{([^}]*)\}/,
};

/** The light (`:root`) and dark (`.dark`) values of THEME_TOKENS, read
 *  from `app/globals.css`. Throws when a block or a token is missing. */
export function readThemeTokens(
  css: string,
): Record<DiagramTheme, Record<string, string>> {
  const read = (theme: DiagramTheme) => {
    const block = BLOCKS[theme].exec(css)?.[1];
    if (block === undefined) {
      throw new Error(`globals.css has no ${theme} token block`);
    }
    const out: Record<string, string> = {};
    for (const token of THEME_TOKENS) {
      const m = new RegExp(`--${token}:\\s*([^;]+);`).exec(block);
      if (!m) throw new Error(`globals.css ${theme} block has no --${token}`);
      out[token] = m[1].trim();
    }
    return out;
  };
  return { light: read("light"), dark: read("dark") };
}

export function diagramStamp(input: {
  mermaidVersion: string;
  theme: DiagramTheme;
  tokens: Record<string, string>;
  source: string;
}): string {
  return createHash("sha256")
    .update(
      JSON.stringify([
        input.mermaidVersion,
        input.theme,
        THEME_TOKENS.map((t) => [t, input.tokens[t]]),
        Object.entries(MERMAID_THEME_MAP),
        input.source,
      ]),
    )
    .digest("hex");
}

const STAMP =
  /^<!-- Generated by web\/scripts\/render-help-diagrams\.mjs from (\S+); do not edit\. stamp: ([0-9a-f]{64}) -->\n/;

export function withStamp(svg: string, from: string, stamp: string): string {
  return `<!-- Generated by web/scripts/render-help-diagrams.mjs from ${from}; do not edit. stamp: ${stamp} -->\n${svg}\n`;
}

/** The stamp a committed SVG was rendered with, or undefined. */
export function readStamp(svg: string): string | undefined {
  return STAMP.exec(svg)?.[2];
}

/**
 * Remove everything active from a rendered SVG: `<script>` elements,
 * `on*` event-handler attributes, and links that are not same-document
 * fragments. Mermaid can emit handlers (its click directive), and the
 * diagram check runs `unsafeSvgParts` over every committed file as well.
 */
export function sanitizeSvg(svg: string): string {
  const clean = svg
    .replace(/<script\b[^>]*\/>/gi, "")
    .replace(/<script\b[\s\S]*?<\/script\s*>/gi, "")
    .replace(/\s+on[a-z]+\s*=\s*("[^"]*"|'[^']*'|[^\s>]+)/gi, "")
    .replace(/\s+(?:xlink:)?href\s*=\s*("(?!#)[^"]*"|'(?!#)[^']*')/gi, "");
  const left = unsafeSvgParts(clean);
  if (left.length > 0) {
    throw new Error(`rendered SVG is still unsafe: ${left.join(", ")}`);
  }
  return clean;
}

/** What makes an SVG unsafe to serve: empty when it is clean. */
export function unsafeSvgParts(svg: string): string[] {
  const out: string[] = [];
  if (/<script\b/i.test(svg)) out.push("<script>");
  if (/\son[a-z]+\s*=/i.test(svg)) out.push("event-handler attribute");
  if (/javascript:/i.test(svg)) out.push("javascript: URL");
  if (/\s(?:xlink:)?href\s*=\s*["'](?!#)/i.test(svg)) {
    out.push("external link");
  }
  if (/<foreignObject\b/i.test(svg)) out.push("<foreignObject>");
  return out;
}
