#!/usr/bin/env bash
# Regenerates internal/api/scfimport/stock_manifests_gen.go: the sha256 of
# every revision of every stock control.yaml under controls/soc2/ that git
# history holds, keyed to its bundle_id (#2321).
#
# The SCF re-bind (#1971 D3, amended by #2321) moves a stock control to the
# current release's anchor when only the anchor's title changed. A control is
# stock when its stored manifest is byte-identical to one the platform
# shipped, so every revision counts: an install bootstrapped from an older
# commit stores that commit's bytes. A tenant cannot get a manifest of its own
# onto this list.
#
# The list is append-only (#2963): the entries already in the generated
# file are kept, and the history walk only adds to them. The walk sees only
# commits reachable from HEAD, and a squash merge drops a PR branch's
# intermediate commits, so a hash added from one of those (or from a
# working-tree edit) vanishes on the next regeneration elsewhere. Three did:
# cc4_1 (#2932 -> #2937), cc6_1 (#2897 -> #2913), cc6_7 (#2948 -> #2955).
# scripts/check-stock-hashes-superset.sh is the CI guard against a drop that
# arrives some other way, such as a merge-conflict resolution.
#
# Run after editing any controls/soc2/*/control.yaml and commit the result;
# TestStockManifestHashes_CoverControlsDir fails until you do.
#
# Usage: bash scripts/gen-stock-control-hashes.sh
set -euo pipefail

root="$(git rev-parse --show-toplevel)"
out="$root/internal/api/scfimport/stock_manifests_gen.go"
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

# Every blob any commit has held at controls/soc2/<dir>/control.yaml, plus
# the working tree's current bytes (an uncommitted edit is about to ship).
{
	git -C "$root" log --format=%H -- 'controls/soc2/*/control.yaml' |
		while read -r commit; do
			git -C "$root" ls-tree -r "$commit" -- controls/soc2 |
				awk '$4 ~ /\/control\.yaml$/ { print $3 }'
		done |
		sort -u |
		while read -r blob; do
			git -C "$root" cat-file blob "$blob" >"$tmp.blob"
			printf '%s %s\n' "$(shasum -a 256 "$tmp.blob" | cut -d' ' -f1)" \
				"$(sed -n 's/^bundle_id:[[:space:]]*"\{0,1\}\([^"[:space:]]*\)"\{0,1\}[[:space:]]*$/\1/p' "$tmp.blob" | head -n1)"
		done
	for f in "$root"/controls/soc2/*/control.yaml; do
		printf '%s %s\n' "$(shasum -a 256 "$f" | cut -d' ' -f1)" \
			"$(sed -n 's/^bundle_id:[[:space:]]*"\{0,1\}\([^"[:space:]]*\)"\{0,1\}[[:space:]]*$/\1/p' "$f" | head -n1)"
	done
	# Keep every entry already on the list.
	if [ -f "$out" ]; then
		sed -n 's/^[[:space:]]*"\([0-9a-f]\{64\}\)":[[:space:]]*"\([^"]*\)",$/\1 \2/p' "$out"
	fi
} | sort -u >"$tmp"
rm -f "$tmp.blob"

if awk 'NF != 2 { bad = 1 } END { exit !bad }' "$tmp"; then
	echo "gen-stock-control-hashes: a control.yaml revision has no bundle_id line" >&2
	exit 1
fi
if [ -n "$(cut -d' ' -f1 "$tmp" | uniq -d)" ]; then
	echo "gen-stock-control-hashes: a hash maps to two bundle_ids:" >&2
	cut -d' ' -f1 "$tmp" | uniq -d >&2
	exit 1
fi

{
	cat <<'EOF'
// Code generated by scripts/gen-stock-control-hashes.sh. DO NOT EDIT.

package scfimport

// stockManifestHashes maps the sha256 of every control.yaml revision the
// platform has shipped under controls/soc2/ to its bundle_id (#2321).
var stockManifestHashes = map[string]string{
EOF
	awk '{ printf "\t\"%s\": \"%s\",\n", $1, $2 }' "$tmp"
	echo "}"
} >"$out"
gofmt -w "$out"
echo "wrote $(wc -l <"$tmp" | tr -d ' ') hashes to ${out#"$root"/}"
